/** UNOFFICIAL, opt-in migration of freshly generated qualification fixtures only. */
import { createHash, randomUUID } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { renderNativeManifest } from '../../src/index.mjs';
import { commandResult, tail } from './qualification.mjs';

export const COMPLETE_HOME_CONTRACT = 'complete-home-v1';
const sha256 = value => createHash('sha256').update(value).digest('hex');
const fail = message => { throw Object.assign(new Error(message), { code: 'CANDIDATE_CONTRACT_INVALID' }); };

/** No inference from a branch name or loader error; callers select the migration explicitly. */
export async function prepareCandidateManifest(directory, { stateContract, revision, nativeContract }) {
  if (stateContract !== COMPLETE_HOME_CONTRACT) fail('Unknown candidate state contract');
  if (!/^[0-9a-f]{40}$/.test(revision) || revision === nativeContract.revision) {
    fail('A candidate manifest migration must not alter the supported pinned contract');
  }
  const manifestPath = path.join(directory, nativeContract.manifest);
  const metadataPath = path.join(directory, nativeContract.metadata);
  const manifest = await readFile(manifestPath, 'utf8');
  const metadata = JSON.parse(await readFile(metadataPath, 'utf8'));
  if (metadata.pack !== 'nemoclaw-native-agent' || metadata.packVersion !== 2 || metadata.qualification !== undefined
      || metadata.contract?.upstream !== nativeContract.upstream || metadata.contract?.revision !== nativeContract.revision
      || manifest !== renderNativeManifest(metadata.agent)) {
    fail('Candidate migration requires a fresh, unmodified package generated by this SDK');
  }
  const inventory = 'state_dirs:\n  - path: sessions\n';
  if (manifest.split(inventory).length !== 2 || /^(?:state_files|runtime_auth_state_dirs):/m.test(manifest)) {
    fail('The generated selective-state manifest contract has changed');
  }
  const migrated = manifest.replace(inventory, '');
  const receipt = {
    stateContract, qualificationOnly: true, targetRevision: revision,
    templateRevision: nativeContract.revision,
    originalManifestSha256: sha256(manifest), manifestSha256: sha256(migrated),
    persistenceVerified: false,
  };
  // Keep the original template provenance and record the explicit override.
  // This disposable fixture is never promoted to the public supported pin.
  await writeFile(manifestPath, migrated);
  await writeFile(metadataPath, JSON.stringify({ ...metadata, qualification: receipt }, null, 2) + '\n');
  return receipt;
}

/** Preserve a rejected loader's diagnostic, without forwarding unbounded provider data. */
export function loaderStage(verification) {
  const accepted = verification.loaderAccepted === true;
  return {
    status: accepted ? 'passed' : 'failed', category: accepted ? undefined : 'product',
    loaderAccepted: accepted, listed: verification.listed, workload: verification.workload,
    checkoutRevision: verification.checkoutRevision,
    ...(!accepted ? {
      errorCode: 'LOADER_REJECTED',
      error: tail(typeof verification.error === 'string'
        ? verification.error : 'The upstream loader did not accept the generated agent package'),
    } : {}),
  };
}

/** Seed and verify only run-unique files; ordinary user files are never overwritten. */
export function persistenceProbeSource(name, token, verify = false) {
  if (!/^[a-z][a-z0-9-]{0,31}$/.test(name) || !/^[0-9a-f-]{36}$/.test(token)) fail('Invalid persistence probe identity');
  const marker = (verify ? 'NHA_STATE_RESTORED:' : 'NHA_STATE_SEEDED:') + token;
  return [
    'const fs = require("node:fs"); const path = require("node:path");',
    'const root = "/sandbox";',
    'const paths = ' + JSON.stringify([
      '.' + name + '/sessions/.nha-qualification-' + token + '/history.json',
      'workspace/.nha-qualification-' + token + '/nested/document.txt',
      '.' + name + '/.nha-qualification-' + token + '/unlisted/custom-state.txt',
    ]) + ';',
    'for (const relative of paths) {',
    '  const target = path.join(root, relative);',
    '  const expected = JSON.stringify({ qualification: ' + JSON.stringify(token) + ', path: relative });',
    verify
      ? '  if (fs.readFileSync(target, "utf8") !== expected) throw new Error("Rebuild did not preserve qualification state: " + relative);'
      : '  fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, expected, { flag: "wx", mode: 0o600 });',
    '}',
    'console.log(' + JSON.stringify(marker) + ');',
  ].join('\n');
}

/** A complete-home candidate must prove persistence, not merely pass the loader. */
export async function qualifyCandidatePersistence({ result, name, cli, execute, env }) {
  const token = randomUUID();
  const sandbox = result.sandbox.name;
  const exec = source => [process.execPath, cli, sandbox, 'exec', '--', 'node', '-e', source];
  const steps = [
    ['state-seed', exec(persistenceProbeSource(name, token)), 'NHA_STATE_SEEDED:' + token],
    ['rebuild', [process.execPath, cli, 'sandbox', 'rebuild', sandbox, '--yes'], null],
    ['state-verify', exec(persistenceProbeSource(name, token, true)), 'NHA_STATE_RESTORED:' + token],
    ['post-rebuild-exec', [process.execPath, cli, sandbox, 'exec', '--', '/usr/local/bin/' + name, 'NHA_COMPAT_REBUILT'], 'Echo: NHA_COMPAT_REBUILT'],
  ];
  for (const [key, argv, marker] of steps) {
    const outcome = await execute(key, argv, { cwd: result.checkout, env, ...(marker ? { marker } : {}) });
    const stage = commandResult(outcome, 'product');
    if (stage.status === 'passed' && marker && !outcome.markerSeen) {
      Object.assign(stage, { status: 'failed', category: 'product', errorCode: 'STATE_SMOKE_MISMATCH' });
    }
    result.stages[key] = stage;
    if (stage.status !== 'passed') {
      result.status = stage.status === 'blocked' ? 'blocked' : 'failed';
      result.failureClass = stage.category ?? 'product';
      return false;
    }
  }
  result.manifestQualification.persistenceVerified = true;
  return true;
}
